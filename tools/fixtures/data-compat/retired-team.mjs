import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {pathToFileURL} from 'node:url';
import {join,resolve} from 'node:path';
import {mkdir,readFile,writeFile} from 'node:fs/promises';
const [runtime,root,label]=process.argv.slice(2);assert(process.env.DSHA_DATA_COMPAT_ROOT && resolve(root).startsWith(resolve(process.env.DSHA_DATA_COMPAT_ROOT)+'/'));
const require=createRequire(join(runtime,'package.json'));
const {loadProfileDirectory}=await import(pathToFileURL(require.resolve('@deepseek-ai/dsh-app-boot')).href);
await mkdir(root,{recursive:true});
const retired='@deepseek-ai/dsh-experimental-agent-team-profile';
const before={private:true,dependencies:{[retired]:'0.2.2-rc.1'},customField:{keep:'yes'},dsh:{profile:{bundles:[retired],unknown:'preserve'}}};
const path=join(root,'package.json');const patch=join(root,'cordis.patch.yml');
await writeFile(path,JSON.stringify(before,null,2)+'\n');await writeFile(patch,'# exact original user bytes\n[]\n');
const original=await readFile(path);const loaded=loadProfileDirectory('audit',root,require.resolve('@deepseek-ai/dsh/package.json'));
const after=JSON.parse(await readFile(path,'utf8'));
assert.deepEqual(after.customField,before.customField);assert.deepEqual(after.dependencies,before.dependencies);assert.equal(after.dsh.profile.unknown,'preserve');assert.equal(await readFile(patch,'utf8'),'# exact original user bytes\n[]\n');
assert.equal(after.dsh.profile.bundles.includes(retired),label==='old');
const report={runtime,label,version:require('@deepseek-ai/dsh/package.json').version,manifestRewritten:!original.equals(await readFile(path)),beforeBundles:before.dsh.profile.bundles,afterBundles:after.dsh.profile.bundles,installedDependencyDeclarationPreserved:true,unknownFieldsPreserved:true,patchBytesPreserved:true,skippedBundles:loaded.skippedBundles};
await writeFile(join(root,'result.json'),JSON.stringify(report,null,2)+'\n');console.log(JSON.stringify(report));
