#!/usr/bin/env python3
"""Draw DSHA's terminal prompt mark from coordinates, with no source artwork or fonts."""
import argparse
from pathlib import Path

from PIL import Image, ImageDraw


RES = Path(__file__).resolve().parents[1] / 'app/src/main/res'
# Adapted from the project's BootLogoView and its UI design in
# docs/design/ui-template-baseline-20261103/pages/onboarding.js (commit bcba41b8).
# The heavier stroke keeps both parts legible in a 24dp notification icon.
STROKES = (((6, 6), (14, 12), (6, 18)), ((13, 18), (20, 18)))
STROKE_WIDTH = 2.4
BACKGROUND = '#193552'
DENSITIES = {'mdpi': 48, 'hdpi': 72, 'xhdpi': 96, 'xxhdpi': 144, 'xxxhdpi': 192}


def vector_xml():
    commands = []
    for stroke in STROKES:
        commands.append('M' + ' L'.join(f'{x},{y}' for x, y in stroke))
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/prepare-app-icon.py from the project's native terminal prompt. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp" android:height="24dp"
    android:viewportWidth="24" android:viewportHeight="24">
    <path android:pathData="{' '.join(commands)}"
        android:strokeColor="#FFFFFFFF" android:strokeWidth="{STROKE_WIDTH}"
        android:strokeLineCap="round" android:strokeLineJoin="round" />
</vector>
'''


def render_tile():
    # Draw once, then downsample separately at every density. Transparent round
    # corners also work on launchers and native pages without an adaptive mask.
    scale = 96
    edge = 24 * scale
    tile = Image.new('RGBA', (edge, edge))
    draw = ImageDraw.Draw(tile)
    draw.rounded_rectangle((0, 0, edge - 1, edge - 1), radius=5 * scale, fill=BACKGROUND)
    width = round(STROKE_WIDTH * scale)
    radius = width / 2
    for stroke in STROKES:
        points = [(x * scale, y * scale) for x, y in stroke]
        draw.line(points, fill='white', width=width)
        for x, y in points:
            draw.ellipse((x - radius, y - radius, x + radius, y + radius), fill='white')
    return tile


def generate(resources):
    vector = resources / 'drawable/ic_dsha_mark.xml'
    vector.parent.mkdir(parents=True, exist_ok=True)
    vector.write_text(vector_xml(), encoding='utf-8', newline='\n')
    outputs = {'drawable-nodpi/dsha_brand.webp': 512}
    outputs.update({f'mipmap-{density}/ic_launcher.webp': size for density, size in DENSITIES.items()})
    tile = render_tile()
    for name, size in outputs.items():
        target = resources / name
        target.parent.mkdir(parents=True, exist_ok=True)
        tile.resize((size, size), Image.Resampling.LANCZOS).save(target, lossless=True, method=6)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--res-dir', type=Path, default=RES)
    generate(parser.parse_args().res_dir)
